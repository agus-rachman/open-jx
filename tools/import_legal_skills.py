#!/usr/bin/env python3
"""Import reference data from the MIT-licensed l0cka/legal-skills repository into open-jx packs.

    git clone --depth 1 https://github.com/l0cka/legal-skills /path/to/legal-skills
    python tools/import_legal_skills.py --upstream /path/to/legal-skills

Writes generated files only (hand-written pack files are never touched):

  packs/<id>/deadlines.yaml   holiday table and court/tribunal computation-rule tables,
                              kept in the upstream structure with their evidence states
  packs/<id>/privacy.yaml     state and territory privacy, health, breach, workplace and
                              automated-decision regimes, as open-jx legal entries

Every generated file records the upstream commit and file paths in `provenance`.
Upstream evidence states are preserved; open-jx reviewer fields (`verified`,
`verified_by`) start empty. Re-run after upstream updates and review the diff.
See THIRD-PARTY-NOTICES.md for the licence.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PACKS = ROOT / "packs"
UPSTREAM_REPO = "https://github.com/l0cka/legal-skills"
BASE = Path("plugins/legal-skills")

STATE = {"NSW": "au-nsw", "VIC": "au-vic", "QLD": "au-qld", "WA": "au-wa", "SA": "au-sa",
         "TAS": "au-tas", "ACT": "au-act", "NT": "au-nt", "Cth": "au"}
RULE_TABLE_PACK = {"cth-federal-courts": "au", "art": "au", "nsw-courts": "au-nsw", "ncat": "au-nsw",
                   "vic-courts": "au-vic", "vcat": "au-vic", "qld-courts": "au-qld", "qcat": "au-qld",
                   "wa-courts": "au-wa", "sa-courts": "au-sa", "tas-courts": "au-tas", "act-courts": "au-act",
                   "nt-courts": "au-nt"}
HOLIDAY_PACK = {"nsw": "au-nsw", "vic": "au-vic", "qld": "au-qld", "wa": "au-wa", "sa": "au-sa",
                "tas": "au-tas", "act": "au-act", "nt": "au-nt"}
ABBR = {"NSW": "NSW", "VIC": "Vic", "QLD": "Qld", "WA": "WA", "SA": "SA", "TAS": "Tas", "ACT": "ACT", "NT": "NT"}
KIND = {"general_privacy": "General privacy law", "health": "Health information", "breach": "Data breach notification",
        "workplace": "Workplace surveillance", "automated_decisions": "Automated decision-making"}
HEADER = ("# GENERATED by tools/import_legal_skills.py from {repo} at commit {sha}.\n"
          "# Licence: MIT (see THIRD-PARTY-NOTICES.md). Do not edit by hand: change upstream or the importer, then re-run.\n")


def dump(path: Path, data: dict, sha: str):
    text = HEADER.format(repo=UPSTREAM_REPO, sha=sha) + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(text, encoding="utf-8")


def status_of(entry: dict, today: dt.date):
    s = (entry.get("status") or "").lower()
    commencement = next((v for k, v in entry.items() if k.startswith("commencement")), None)
    if s == "current legislation":
        if commencement and dt.date.fromisoformat(commencement) > today:
            return "pending", commencement
        return "in-force", None
    if s == "enacted future legislation":
        return "pending", commencement
    if s == "binding administrative instruction":
        return "in-force", None
    return "guidance", None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--upstream", type=Path, required=True, help="path to a legal-skills checkout")
    args = ap.parse_args()
    up = args.upstream.resolve()
    sha = subprocess.run(["git", "-C", str(up), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip() or "unknown"
    refs = up / BASE / "references"
    today = dt.date.today()

    deadlines: dict[str, dict] = {}

    def bucket(pid):
        return deadlines.setdefault(pid, {"provenance": {"source": UPSTREAM_REPO, "commit": sha, "licence": "MIT",
                                                         "files": [], "imported": today.isoformat()},
                                          "holiday_table": None, "court_rules": []})

    for f in sorted((refs / "holidays").glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        pid = HOLIDAY_PACK[data["table_id"]]
        b = bucket(pid)
        b["holiday_table"] = data
        b["provenance"]["files"].append(str(f.relative_to(up)))
    for f in sorted((refs / "computation-rules").glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        pid = RULE_TABLE_PACK[data["table_id"]]
        b = bucket(pid)
        b["court_rules"].append(data)
        b["provenance"]["files"].append(str(f.relative_to(up)))
    for pid, data in deadlines.items():
        dump(PACKS / pid / "deadlines.yaml", data, sha)
        print(f"wrote packs/{pid}/deadlines.yaml ({len(data['court_rules'])} rule tables, holidays: {bool(data['holiday_table'])})")

    cov_path = up / BASE / "skills/route-australian-privacy-jurisdiction/references/state-territory-coverage.json"
    cov = json.loads(cov_path.read_text(encoding="utf-8"))
    for j in cov["jurisdictions"]:
        pid = STATE[j["code"]]
        entries = []
        for kind, e in j.items():
            if not isinstance(e, dict):
                continue
            status, commences = status_of(e, today)
            label = KIND.get(kind, kind.replace("_", " ").capitalize())
            if (e.get("status") or "").lower() == "not identified":
                observe = f"{label}: no dedicated regime identified in this jurisdiction (upstream as at {cov['as_at']})."
            else:
                observe = f"{label}: {e['title']}" + (f" — {e['scope']}" if e.get("scope") else "") + f" ({e.get('status')})."
            authority = e["title"]
            if " Act " in f"{authority} " and not re.search(r"\((Cth|NSW|Vic|Qld|WA|SA|Tas|ACT|NT)\)", authority):
                authority = f"{authority} ({ABBR[j['code']]})"
            entry = {"id": f"{pid}.privacy.{kind.replace('_', '-')}", "observe": observe, "authority": authority,
                     "source_url": e["official_url"], "status": status}
            if commences:
                entry["commences"] = commences
            other = {k: v for k, v in e.items() if k.startswith("commencement") and v != commences}
            if other:
                entry["note"] = "; ".join(f"{k.replace('_', ' ')}: {v}" for k, v in other.items())
            entry.update({"verified": None, "verified_by": None,
                          "provenance": {"source": UPSTREAM_REPO, "commit": sha, "path": str(cov_path.relative_to(up)),
                                         "upstream_checked": e.get("last_verified"), "upstream_state": "verified"}})
            entries.append(entry)
        dump(PACKS / pid / "privacy.yaml", {"privacy_regimes": entries}, sha)
        print(f"wrote packs/{pid}/privacy.yaml ({len(entries)} regimes)")


if __name__ == "__main__":
    main()
